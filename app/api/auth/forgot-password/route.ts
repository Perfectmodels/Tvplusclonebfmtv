import {NextRequest} from 'next/server';
import {z} from 'zod';
import {createAuthClient} from '../../../../lib/auth/server';
import {canonicalSiteUrl} from '../../../../lib/articles/site-url';
import {recoveryConfigured,setRecoveryIntent} from '../../../../lib/auth/recovery';
import {safeReturnPath} from '../../../../lib/auth/return-path';
import {rateLimit} from '../../../../lib/api/rate-limit';
import {handleRoute,ok,ApiError} from '../../../../lib/api/response';
import {emailSchema,parseJson} from '../../../../lib/api/validate';
export const dynamic='force-dynamic';
export const POST=handleRoute(async(req:NextRequest)=>{
 if(req.headers.get('origin')!==req.nextUrl.origin)throw new ApiError('Origine refusée.',403,'UNAUTHORIZED');
 const {email,next}=parseJson(z.object({email:emailSchema,next:z.string().max(1000).optional()}),await req.json());
 rateLimit(req,{prefix:'recovery-ip',limit:20,windowMs:600000});
 rateLimit(req,{prefix:'recovery-account',limit:3,windowMs:600000,subject:email});
 if(!recoveryConfigured())throw new ApiError('Le service de récupération est temporairement indisponible.',503,'UNAVAILABLE');
 const db=await createAuthClient();const url=new URL('/auth/callback?flow=recovery',canonicalSiteUrl());
 const destination=safeReturnPath(next,'');if(destination)url.searchParams.set('next',destination);
 const {error}=await db.auth.resetPasswordForEmail(email.trim().toLowerCase(),{redirectTo:url.href});
 if(error?.status===429)throw new ApiError('Le service d’envoi a atteint sa limite. Réessayez ultérieurement.',429,'RATE_LIMITED');
 if(error&&(!error.status||error.status>=500))throw new ApiError('Envoi temporairement indisponible. Réessayez ultérieurement.',503,'UNAVAILABLE');
 if(!error)await setRecoveryIntent(email);
 return ok({sent:true});
});
